"""Tests for mesh export and import (round-trip)."""

import os
import struct
import pytest

from mcengine import (
    MarchingCubes, SphereSampler, analyze_mesh,
    write_obj, write_off, write_ply_ascii, write_ply_binary,
    write_stl_ascii, write_stl_binary, write_gltf_minimal,
    read_obj, read_off, read_ply_ascii, read_stl_ascii, read_stl_binary,
    read_mesh,
)
from tests.conftest import temp_file, cleanup, assert_mesh_valid


@pytest.fixture
def sphere_mesh():
    mc = MarchingCubes(SphereSampler(1.0), resolution=(16, 16, 16))
    return mc.run()


class TestOBJ:
    def test_write_read_roundtrip(self, sphere_mesh):
        path = temp_file(".obj")
        try:
            write_obj(sphere_mesh, path)
            assert os.path.exists(path)
            loaded = read_obj(path)
            assert loaded.num_vertices == sphere_mesh.num_vertices
            assert loaded.num_faces == sphere_mesh.num_faces
        finally:
            cleanup(path)

    def test_file_contents(self, sphere_mesh):
        path = temp_file(".obj")
        try:
            write_obj(sphere_mesh, path)
            with open(path) as f:
                content = f.read()
            assert content.startswith("# Generated by mcengine")
            assert "v " in content
            assert "f " in content
        finally:
            cleanup(path)


