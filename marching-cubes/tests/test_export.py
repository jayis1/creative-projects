class TestSTL:
    def test_ascii_roundtrip(self, sphere_mesh):
        path = temp_file(".stl")
        try:
            write_stl_ascii(sphere_mesh, path)
            loaded = read_stl_ascii(path)
            assert_mesh_valid(loaded)
        finally:
            cleanup(path)

    def test_binary_header_is_80_bytes(self, sphere_mesh):
        """Binary STL header must be exactly 80 bytes."""
        path = temp_file(".stl")
        try:
            write_stl_binary(sphere_mesh, path)
            with open(path, "rb") as f:
                header = f.read(80)
                assert len(header) == 80
                face_count = struct.unpack("<I", f.read(4))[0]
                assert face_count == sphere_mesh.num_faces
        finally:
            cleanup(path)

    def test_binary_roundtrip(self, sphere_mesh):
        path = temp_file(".stl")
        try:
            write_stl_binary(sphere_mesh, path)
            loaded = read_stl_binary(path)
            assert_mesh_valid(loaded)
            # STL doesn't share vertices, so loaded mesh may have more vertices
            # but should have same face count
            assert loaded.num_faces == sphere_mesh.num_faces
        finally:
            cleanup(path)


class TestglTF:
    def test_write_gltf(self, sphere_mesh):
        import json
        path = temp_file(".gltf")
        try:
            write_gltf_minimal(sphere_mesh, path)
            with open(path) as f:
                data = json.load(f)
            assert data["asset"]["version"] == "2.0"
            assert data["asset"]["generator"] == "mcengine"
            assert len(data["meshes"]) == 1
        finally:
            cleanup(path)


